export function getCountryCodeByName(name: string): string {
  if (!name) return 'un';
  const clean = name.trim().toLowerCase();
  const match = ALL_COUNTRIES.find(c => c.name.toLowerCase() === clean);
  if (match) return match.code;
  const partial = ALL_COUNTRIES.find(c => c.name.toLowerCase().includes(clean) || clean.includes(c.name.toLowerCase()));
  return partial ? partial.code : 'un';
}
